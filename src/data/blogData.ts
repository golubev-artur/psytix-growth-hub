export const getPsychologyPosts = () =>
  blogPosts.filter((p) => p.category === 'psychology');

export const getSalesPosts = () =>
  blogPosts.filter((p) => p.category === 'sales');

export const getPostById = (id: string) =>
  blogPosts.find((p) => p.id === id);

export const getRelatedPosts = (ids: string[]) =>
  ids.map((id) => getPostById(id)).filter(Boolean) as BlogPost[];

export const getPostUrl = (post: BlogPost): string => {
  const cat = post.category === 'psychology' ? 'psy' : 'sal';
  return `/blog/${cat}/${post.slug}`;
};
